"""
core/reporter.py
Takes a completed session log + anomaly list and writes a markdown bug report.
No LLM — pure structured data formatting.
(Week 4 will add LLM-written bug descriptions on top of this.)
"""
import json
from datetime import datetime
from pathlib import Path

REPORTS_DIR = Path(__file__).parent.parent / "outputs" / "reports"
SEVERITY_EMOJI = {"high": "🔴", "medium": "🟡", "low": "🟢"}
TYPE_LABEL = {
    "js_error":            "JavaScript Error",
    "slow_load":           "Slow Page Load",
    "action_failure":      "Action Failed",
    "page_frozen":         "Page Frozen / No Change",
    "unexpected_redirect": "Unexpected Redirect",
    "blank_page":          "Blank / Empty Page",
}


def generate_report(
    session_id: str,
    target_url: str,
    actions_log: list,
    anomalies: list,
    page_info: dict | None = None,
) -> str:
    now     = datetime.now().strftime("%Y-%m-%d %H:%M")
    high    = [a for a in anomalies if a["severity"] == "high"]
    medium  = [a for a in anomalies if a["severity"] == "medium"]
    low     = [a for a in anomalies if a["severity"] == "low"]

    lines = []
    lines += [
        f"# ProductValidation OS — Bug Report",
        f"",
        f"| Field | Value |",
        f"|---|---|",
        f"| Session ID | `{session_id}` |",
        f"| Target URL | {target_url} |",
        f"| Generated  | {now} |",
        f"| Steps run  | {len(actions_log)} |",
        f"| Bugs found | {len(anomalies)} ({len(high)} high / {len(medium)} medium / {len(low)} low) |",
        f"",
        f"---",
        f"",
    ]

    if not anomalies:
        lines += [
            "## ✅ No Issues Found",
            "",
            "All steps completed without detected anomalies.",
            "",
        ]
    else:
        lines += ["## 🐛 Bugs Found", ""]
        for i, a in enumerate(anomalies, 1):
            emoji = SEVERITY_EMOJI.get(a["severity"], "⚪")
            label = TYPE_LABEL.get(a["type"], a["type"])
            lines += [
                f"### Bug {i}: {emoji} {label}",
                f"",
                f"- **Severity**: {a['severity'].upper()}",
                f"- **Step**: {a.get('step', 'N/A')}",
                f"- **Detail**: {a.get('detail', '')}",
            ]
            if "url" in a:
                lines.append(f"- **URL**: {a['url']}")
            if "diff_pct" in a:
                lines.append(f"- **Pixel diff**: {a['diff_pct']*100:.1f}%")
            # link to screenshot
            screenshot_path = None
            for act in actions_log:
                if act.get("step") == a.get("step") and act.get("screenshot"):
                    screenshot_path = act["screenshot"].get("filename")
                    break
            if screenshot_path:
                lines.append(f"- **Screenshot**: `outputs/screenshots/{screenshot_path}`")
            lines.append("")

    # Step log table
    lines += [
        "---",
        "",
        "## 📋 Step Log",
        "",
        "| Step | Action | Target | Status | Time |",
        "|---|---|---|---|---|",
    ]
    for act in actions_log:
        status = "✅" if act.get("success") else "❌"
        target = str(list(act["params"].values())[0])[:40] if act["params"] else ""
        ms     = act.get("duration_ms", 0)
        lines.append(
            f"| {act['step']} | {act['action']} | `{target}` | {status} | {ms}ms |"
        )

    lines += ["", "---", "", "*Generated by ProductValidation OS — Week 1 build*", ""]

    report_text = "\n".join(lines)
    out_path    = REPORTS_DIR / f"{session_id}_report.md"
    out_path.write_text(report_text)
    print(f"[report saved] {out_path}")
    return report_text


def save_anomalies_json(session_id: str, anomalies: list) -> str:
    out = REPORTS_DIR / f"{session_id}_anomalies.json"
    out.write_text(json.dumps(anomalies, indent=2))
    return str(out)


# ── full pipeline report (crawl + vision + PRD + QA + PM + debate +  ───────
# ── impact score + video + tests). Used by the API/dashboard pipeline. ─────

def generate_full_report(
    session_id: str,
    target_url: str,
    scored_bugs: list,
    videos: list,
    test_files: list,
    prd_coverage: dict,
    pm_result: dict,
) -> str:
    """Build the polished final markdown report for a validation run.

    Mirrors the report produced by the Week-4 CLI runner, so a run started
    from the dashboard gets the same level of detail (business impact,
    repro videos, generated tests) instead of the bare mid-pipeline report.
    """
    video_map = {v["bug_id"]: v["video_path"] for v in videos}
    test_map  = {t["bug_id"]: t["filename"]   for t in test_files}

    critical = [b for b in scored_bugs if b.get("final_severity") == "critical"]
    high     = [b for b in scored_bugs if b.get("final_severity") == "high"]
    medium   = [b for b in scored_bugs if b.get("final_severity", "") == "medium"]
    low      = [b for b in scored_bugs if b.get("final_severity", "") == "low"]

    lines = [
        "# ProductValidation OS — Final Report",
        "",
        f"**Session**: `{session_id}`",
        f"**Target**: {target_url}",
        f"**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "",
        "---",
        "",
        "## Executive Summary",
        "",
        pm_result.get("executive_summary", "No PM summary available."),
        "",
        "## Bug Summary",
        "",
        "| Severity | Count |",
        "|---|---|",
        f"| Critical | {len(critical)} |",
        f"| High | {len(high)} |",
        f"| Medium | {len(medium)} |",
        f"| Low | {len(low)} |",
        f"| **Total** | **{len(scored_bugs)}** |",
        "",
    ]

    if prd_coverage:
        pct = prd_coverage.get("coverage_pct", 0)
        lines += ["## PRD Coverage", "", f"**{pct}%** of required pages tested", ""]
        for p in prd_coverage.get("uncovered_pages", []):
            lines.append(f"- NOT TESTED: `{p['path']}` — {p['name']}")
        lines.append("")

    lines += [
        "## Bugs by Business Impact",
        "",
        "| Score | Impact | Bug | Severity | Video | Test |",
        "|---|---|---|---|---|---|",
    ]
    for b in scored_bugs:
        bid   = b.get("id", "?")
        score = b.get("impact_score", 0)
        label = b.get("impact_label", "")
        sev   = b.get("final_severity", b.get("severity", "?"))
        vid   = "Yes" if bid in video_map else "—"
        tst   = f"`{test_map[bid]}`" if bid in test_map else "—"
        lines.append(f"| {score}/100 | {label} | {b.get('title','')} | {sev.upper()} | {vid} | {tst} |")

    lines += ["", "---", "", "## Detailed Bug Reports", ""]

    for bug in scored_bugs:
        bid = bug.get("id", "?")
        sev = bug.get("final_severity", bug.get("severity", "?"))

        lines += [
            f"### {bid}: {bug.get('title','Untitled')}",
            "",
            "| Field | Value |",
            "|---|---|",
            f"| Severity | {sev.upper()} |",
            f"| Business Impact | {bug.get('impact_score',0)}/100 — {bug.get('impact_label','')} |",
            f"| Revenue Risk | {bug.get('estimated_loss','')} |",
            f"| URL | `{bug.get('url','')}` |",
            f"| Fix time | {bug.get('estimated_fix_time','')} |",
            "",
        ]

        steps = bug.get("steps_to_reproduce", [])
        if steps:
            lines.append("**Steps to reproduce:**")
            for i, s in enumerate(steps, 1):
                lines.append(f"{i}. {s}")
            lines.append("")

        if bug.get("expected"):
            lines.append(f"**Expected**: {bug['expected']}")
        if bug.get("actual"):
            lines.append(f"**Actual**: {bug['actual']}")
        if bug.get("fix_recommendation"):
            lines.append(f"**Fix**: {bug['fix_recommendation']}")
        if bug.get("reasoning"):
            lines.append(f"**Why valid**: {bug['reasoning']}")

        if bid in video_map:
            lines.append(f"**Repro video**: `{video_map[bid]}`")
        if bid in test_map:
            lines.append(f"**Playwright test**: `outputs/tests/{test_map[bid]}`")

        lines.append("")

    lines += ["---", "", "*Generated by ProductValidation OS*"]

    report = "\n".join(lines)
    out = REPORTS_DIR / f"{session_id}_final_report.md"
    out.write_text(report)
    print(f"  [Report] Saved: {out}")
    return report