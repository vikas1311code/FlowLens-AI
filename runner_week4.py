"""
runner_week4.py
Week 4 — Full pipeline:
  Week 3 multi-agent graph + Video recording + Test generation + Impact scoring

Usage:
  python runner_week4.py http://localhost:5001 --steps 10 --prd testshop_prd.md
"""
import argparse
import json
import time
from pathlib import Path

from graph import build_graph
from agents.video_recorder import VideoRecorder
from agents.test_generator import TestGenerator
from agents.impact_scorer  import score_all

REPORTS_DIR = Path("outputs/reports")
REPORTS_DIR.mkdir(parents=True, exist_ok=True)


def generate_final_report(session_id: str, target_url: str,
                           scored_bugs: list, videos: list,
                           test_files: list, prd_coverage: dict,
                           pm_result: dict) -> str:

    video_map = {v["bug_id"]: v["video_path"] for v in videos}
    test_map  = {t["bug_id"]: t["filename"]   for t in test_files}

    critical = [b for b in scored_bugs if b.get("final_severity") == "critical"]
    high     = [b for b in scored_bugs if b.get("final_severity") == "high"]
    medium   = [b for b in scored_bugs if b.get("final_severity","") == "medium"]
    low      = [b for b in scored_bugs if b.get("final_severity","") == "low"]

    lines = [
        "# ProductValidation OS — Final Report (Week 4)",
        "",
        f"**Session**: `{session_id}`",
        f"**Target**: {target_url}",
        f"**Generated**: {time.strftime('%Y-%m-%d %H:%M')}",
        "",
        "---",
        "",
        "## Executive Summary",
        "",
        pm_result.get("executive_summary", ""),
        "",
        "## Bug Summary",
        "",
        "| Severity | Count |",
        "|---|---|",
        f"| 🔴 Critical | {len(critical)} |",
        f"| 🔴 High | {len(high)} |",
        f"| 🟡 Medium | {len(medium)} |",
        f"| 🟢 Low | {len(low)} |",
        f"| **Total** | **{len(scored_bugs)}** |",
        "",
    ]

    if prd_coverage:
        pct = prd_coverage.get("coverage_pct", 0)
        lines += [
            "## PRD Coverage",
            "",
            f"**{pct}%** of required pages tested",
            "",
        ]
        for p in prd_coverage.get("uncovered_pages", []):
            lines.append(f"- ❌ `{p['path']}` — {p['name']}")
        lines.append("")

    lines += [
        "## 📊 Bugs by Business Impact",
        "",
        "| Score | Impact | Bug | Severity | Video | Test |",
        "|---|---|---|---|---|---|",
    ]
    for b in scored_bugs:
        bid   = b.get("id","?")
        score = b.get("impact_score", 0)
        label = b.get("impact_label","")
        sev   = b.get("final_severity", b.get("severity","?"))
        vid   = "🎥 Yes" if bid in video_map else "—"
        tst   = f"`{test_map[bid]}`" if bid in test_map else "—"
        lines.append(f"| {score}/100 | {label} | {b.get('title','')} | {sev.upper()} | {vid} | {tst} |")

    lines += ["", "---", ""]
    lines += ["## 🐛 Detailed Bug Reports", ""]

    for bug in scored_bugs:
        bid   = bug.get("id","?")
        sev   = bug.get("final_severity", bug.get("severity","?"))
        emoji = {"critical":"🔴","high":"🔴","medium":"🟡","low":"🟢"}.get(sev,"⚪")

        lines += [
            f"### {emoji} {bid}: {bug.get('title','Untitled')}",
            "",
            f"| Field | Value |",
            f"|---|---|",
            f"| Severity | {sev.upper()} |",
            f"| Business Impact | {bug.get('impact_score',0)}/100 — {bug.get('impact_label','')} |",
            f"| Revenue Risk | {bug.get('estimated_loss','')} |",
            f"| URL | `{bug.get('url','')}` |",
            f"| Fix time | {bug.get('estimated_fix_time','')} |",
            "",
        ]

        steps = bug.get("steps_to_reproduce", [])
        if steps:
            lines.append("**Steps to reproduce:**")
            for i, s in enumerate(steps, 1):
                lines.append(f"{i}. {s}")
            lines.append("")

        if bug.get("expected"):
            lines.append(f"**Expected**: {bug['expected']}")
        if bug.get("actual"):
            lines.append(f"**Actual**: {bug['actual']}")
        if bug.get("fix_recommendation"):
            lines.append(f"**Fix**: {bug['fix_recommendation']}")

        if bid in video_map:
            lines.append(f"**Repro video**: `{video_map[bid]}`")
        if bid in test_map:
            lines.append(f"**Playwright test**: `outputs/tests/{test_map[bid]}`")

        lines.append("")

    lines += ["---", "", "*Generated by ProductValidation OS — Week 4*"]

    report = "\n".join(lines)
    out    = REPORTS_DIR / f"{session_id}_w4_final_report.md"
    out.write_text(report)
    print(f"  [Report] Saved: {out}")
    return report


def main():
    parser = argparse.ArgumentParser(description="ProductValidation OS — Week 4")
    parser.add_argument("url",          help="Target URL")
    parser.add_argument("--steps",      type=int,  default=10)
    parser.add_argument("--prd",        type=str,  default=None)
    parser.add_argument("--no-video",   action="store_true", help="Skip video recording")
    parser.add_argument("--no-tests",   action="store_true", help="Skip test generation")
    args = parser.parse_args()

    session_id = f"pvos_w4_{int(time.time())}"

    print(f"\n{'='*55}")
    print(f"  ProductValidation OS — Week 4")
    print(f"  Session : {session_id}")
    print(f"  Target  : {args.url}")
    print(f"  Pipeline: Crawl→Vision→PRD→QA→PM→Debate→Video→Tests→Score")
    print(f"{'='*55}")

    # ── Phase 1: Week 3 multi-agent graph ────────────────────────────────
    graph = build_graph()
    initial_state = {
        "session_id":       session_id,
        "target_url":       args.url,
        "max_steps":        args.steps,
        "prd_path":         args.prd,
        "actions_log":      [],
        "anomalies":        [],
        "vision_analyses":  [],
        "prd_requirements": {},
        "prd_coverage":     {},
        "qa_result":        {},
        "pm_result":        {},
        "debate_verdicts":  [],
        "final_bugs":       [],
        "final_report":     "",
    }
    state = graph.invoke(initial_state)

    final_bugs = state.get("final_bugs", [])
    pm_result  = state.get("pm_result", {})
    prd_cov    = state.get("prd_coverage", {})

    if not final_bugs:
        print("\n[Week 4] No validated bugs found. Nothing to record/test/score.")
        return

    # ── Phase 2: Business impact scoring ─────────────────────────────────
    print(f"\n{'─'*50}")
    print(f"  PHASE 2: Business Impact Scoring")
    print(f"{'─'*50}")
    pm_reviewed = pm_result.get("reviewed_bugs", [])
    scored_bugs = score_all(final_bugs, pm_reviewed)

    # ── Phase 3: Video recording ─────────────────────────────────────────
    videos = []
    if not args.no_video:
        print(f"\n{'─'*50}")
        print(f"  PHASE 3: Bug Repro Video Recording")
        print(f"{'─'*50}")
        recorder = VideoRecorder(base_url=args.url)
        videos   = recorder.record_all(scored_bugs, session_id, only_high=True)

    # ── Phase 4: Playwright test generation ──────────────────────────────
    test_files = []
    if not args.no_tests:
        print(f"\n{'─'*50}")
        print(f"  PHASE 4: Playwright Test Generation")
        print(f"{'─'*50}")
        generator  = TestGenerator(base_url=args.url)
        test_files = generator.generate_all(scored_bugs)

    # ── Phase 5: Final report ─────────────────────────────────────────────
    print(f"\n{'─'*50}")
    print(f"  PHASE 5: Final Report")
    print(f"{'─'*50}")
    generate_final_report(
        session_id=session_id,
        target_url=args.url,
        scored_bugs=scored_bugs,
        videos=videos,
        test_files=test_files,
        prd_coverage=prd_cov,
        pm_result=pm_result,
    )

    # ── Final summary ─────────────────────────────────────────────────────
    print(f"\n{'='*55}")
    print(f"  WEEK 4 COMPLETE 🎉")
    print(f"{'='*55}")
    print(f"  Validated bugs   : {len(scored_bugs)}")
    print(f"  Videos recorded  : {len(videos)}")
    print(f"  Tests generated  : {len(test_files)}")
    if prd_cov:
        print(f"  PRD coverage     : {prd_cov.get('coverage_pct',0)}%")
    top = scored_bugs[0] if scored_bugs else {}
    if top:
        print(f"  Top priority bug : [{top.get('impact_score',0)}/100] {top.get('title','')}")
    print(f"  Report           : outputs/reports/{session_id}_w4_final_report.md")
    print(f"  Playwright tests : outputs/tests/")
    print(f"  Videos           : outputs/videos/{session_id}/")
    print(f"{'='*55}\n")


if __name__ == "__main__":
    main()
